create or replace function public.class_a_verify_live_attendance(
  p_pass_code text,
  p_live_code text
)
returns table(
  outcome text,
  enrollment_id uuid,
  registration_id bigint,
  session_id uuid,
  attended_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_enrollment public.class_a_session_enrollments%rowtype;
  v_live public.class_a_live_checkin_codes%rowtype;
  v_now timestamptz := now();
begin
  select * into v_enrollment
  from public.class_a_session_enrollments e
  where e.pass_code_hash=encode(extensions.digest(upper(btrim(coalesce(p_pass_code,''))),'sha256'),'hex')
  for update;

  if v_enrollment.id is null then
    return query select 'invalid_pass'::text, null::uuid, null::bigint, null::uuid, null::timestamptz;
    return;
  end if;

  select * into v_live
  from public.class_a_live_checkin_codes c
  where c.session_id=v_enrollment.session_id
    and c.code_hash=encode(extensions.digest(upper(btrim(coalesce(p_live_code,''))),'sha256'),'hex')
    and c.invalidated_at is null
    and v_now between c.opens_at and c.closes_at
  order by c.created_at desc
  limit 1;

  if v_live.id is null then
    return query select 'invalid_or_expired_live_code'::text, v_enrollment.id,
      v_enrollment.registration_id, v_enrollment.session_id, v_enrollment.attended_at;
    return;
  end if;

  if v_enrollment.attended_at is null then
    update public.class_a_session_enrollments
      set status='attended', attended_at=v_now, attendance_source='live_code', updated_at=v_now
    where id=v_enrollment.id
    returning class_a_session_enrollments.attended_at into v_enrollment.attended_at;

    insert into public.class_a_session_attendance_evidence(
      enrollment_id, registration_id, session_id, evidence_type, evidence_at,
      metadata
    ) values (
      v_enrollment.id, v_enrollment.registration_id, v_enrollment.session_id,
      'live_code', v_now, jsonb_build_object('live_code_id',v_live.id)
    );
  end if;

  return query select
    case when v_enrollment.attended_at=v_now then 'attended'::text else 'already_attended'::text end,
    v_enrollment.id, v_enrollment.registration_id, v_enrollment.session_id, v_enrollment.attended_at;
end;
$$;

revoke all on function public.class_a_verify_live_attendance(text,text) from public;
grant execute on function public.class_a_verify_live_attendance(text,text) to anon, authenticated;

