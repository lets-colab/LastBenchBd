create or replace function private.class_a_queue_session_notifications(
  p_enrollment_id uuid
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_enrollment public.class_a_session_enrollments%rowtype;
  v_session public.class_a_sessions%rowtype;
begin
  select * into v_enrollment
  from public.class_a_session_enrollments
  where id = p_enrollment_id;

  if v_enrollment.id is null then return; end if;

  select * into v_session
  from public.class_a_sessions
  where id = v_enrollment.session_id;

  if v_session.id is null then return; end if;

  insert into public.class_a_session_notifications(
    enrollment_id, registration_id, session_id, notification_type, due_at
  ) values (
    v_enrollment.id, v_enrollment.registration_id, v_session.id,
    'registration_confirmation', now()
  )
  on conflict (enrollment_id, notification_type) do nothing;

  if v_session.status in ('scheduled','live') and v_session.starts_at is not null then
    insert into public.class_a_session_notifications(
      enrollment_id, registration_id, session_id, notification_type, due_at
    ) values (
      v_enrollment.id, v_enrollment.registration_id, v_session.id,
      'calendar_invite', now()
    )
    on conflict (enrollment_id, notification_type) do nothing;

    if v_session.starts_at - interval '24 hours' > now() then
      insert into public.class_a_session_notifications(
        enrollment_id, registration_id, session_id, notification_type, due_at
      ) values (
        v_enrollment.id, v_enrollment.registration_id, v_session.id,
        'reminder_24h', v_session.starts_at - interval '24 hours'
      )
      on conflict (enrollment_id, notification_type) do update
        set due_at = excluded.due_at
        where public.class_a_session_notifications.status in ('pending','failed');
    end if;

    if v_session.starts_at - interval '6 hours' > now() then
      insert into public.class_a_session_notifications(
        enrollment_id, registration_id, session_id, notification_type, due_at
      ) values (
        v_enrollment.id, v_enrollment.registration_id, v_session.id,
        'reminder_6h', v_session.starts_at - interval '6 hours'
      )
      on conflict (enrollment_id, notification_type) do update
        set due_at = excluded.due_at
        where public.class_a_session_notifications.status in ('pending','failed');
    end if;

    if v_session.starts_at - interval '15 minutes' > now() then
      insert into public.class_a_session_notifications(
        enrollment_id, registration_id, session_id, notification_type, due_at
      ) values (
        v_enrollment.id, v_enrollment.registration_id, v_session.id,
        'room_open', v_session.starts_at - interval '15 minutes'
      )
      on conflict (enrollment_id, notification_type) do update
        set due_at = excluded.due_at
        where public.class_a_session_notifications.status in ('pending','failed');
    end if;

    insert into public.class_a_session_notifications(
      enrollment_id, registration_id, session_id, notification_type, due_at
    ) values (
      v_enrollment.id, v_enrollment.registration_id, v_session.id,
      'post_class_followup',
      coalesce(v_session.ends_at, v_session.starts_at + interval '2 hours') + interval '10 minutes'
    )
    on conflict (enrollment_id, notification_type) do update
      set due_at = excluded.due_at
      where public.class_a_session_notifications.status in ('pending','failed');
  end if;
end;
$$;

revoke all on function private.class_a_queue_session_notifications(uuid) from public, anon, authenticated;

